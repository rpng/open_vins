#!/usr/bin/env bash
set -euo pipefail

repo_root=/home/himkesh/open_vins_conformal
dataset_root=/mnt/euro_mav
dump_root=/mnt/euro_mav/conformal_dumps
stage2_dir="${dump_root}/stage2"
stage3_dir="${dump_root}/stage3_all11"
input_dir="${stage3_dir}/inputs"
prediction_dir="${stage3_dir}/predictions"
sidecar_dir="${stage3_dir}/sidecars"
run_dir="${stage3_dir}/runs"
log_dir="${stage3_dir}/logs"
report_dir="${stage3_dir}/reports"
stage1_image=openvins-conformal:stage1
stage3_image=openvins-conformal:stage3-exact
pytorch_image=rocm/pytorch:latest

sequences=(
  MH_01_easy MH_02_easy MH_03_medium MH_04_difficult MH_05_difficult
  V1_01_easy V1_02_medium V1_03_difficult
  V2_01_easy V2_02_medium V2_03_difficult
)
declare -A start_offsets=(
  [MH_01_easy]=40
  [MH_02_easy]=35
  [MH_03_medium]=5
  [MH_04_difficult]=10
  # The independent Stage-3 pilot established that MH05 is stable from zero;
  # its old Stage-1 run at 5 s diverged and must not be reused as a baseline.
  [MH_05_difficult]=0
  [V1_01_easy]=0
  [V1_02_medium]=0
  [V1_03_difficult]=0
  [V2_01_easy]=0
  [V2_02_medium]=0
  [V2_03_difficult]=0
)
nonstock_arms=(learned conformalised oracle)
failures=()

mkdir -p "${input_dir}" "${prediction_dir}" "${sidecar_dir}" \
  "${run_dir}" "${log_dir}" "${report_dir}"

docker build \
  -f "${repo_root}/conformal/Dockerfile.stage1.incremental" \
  -t "${stage3_image}" \
  "${repo_root}" \
  2>&1 | tee "${log_dir}/build_stage3_image.log"

run_filter() {
  local sequence=$1
  local arm=$2
  local output="/data/conformal_dumps/stage3_all11/runs/${sequence}_${arm}.h5"
  local command=(
    /catkin_ws/devel/lib/conformal_stage1/run_asl_msckf
    /catkin_ws/src/open_vins/config/euroc_mav/estimator_config.yaml
    "/data/${sequence}" "${sequence}" "${output}" "${start_offsets[$sequence]}"
  )
  if [[ "${arm}" != stock ]]; then
    command+=("/data/conformal_dumps/stage3_all11/sidecars/${sequence}_${arm}_sigma.h5")
  fi
  if ! docker run --rm \
    --user "$(id -u):$(id -g)" \
    -v "${dataset_root}:/data" \
    "${stage3_image}" \
    "${command[@]}" \
    2>&1 | tee "${log_dir}/${sequence}_${arm}.log"; then
    failures+=("${sequence}_${arm}:runner")
    return 1
  fi
  if ! docker run --rm \
    --user "$(id -u):$(id -g)" \
    -v "${dataset_root}:/data" \
    "${stage3_image}" \
    python3 /catkin_ws/src/open_vins/conformal/stage1_dumps/validate_dump.py \
    "${output}" \
    2>&1 | tee "${log_dir}/${sequence}_${arm}.validation.log"; then
    failures+=("${sequence}_${arm}:validation")
    return 1
  fi
  if [[ "${arm}" != stock ]]; then
    local lookup_rate
    lookup_rate=$(
      sed -n \
        's/^.*sigma lookup hits=[0-9][0-9]* queries=[0-9][0-9]* hit_rate=//p' \
        "${log_dir}/${sequence}_${arm}.log" |
        tail -n 1
    )
    if [[ -z "${lookup_rate}" ]] ||
       ! awk -v rate="${lookup_rate}" 'BEGIN { exit !(rate + 0 >= 0.99) }'; then
      failures+=("${sequence}_${arm}:exact-sigma-lookup-below-0.99")
      printf 'FAIL hit_rate=%s minimum=0.99\n' "${lookup_rate:-missing}" \
        | tee "${log_dir}/${sequence}_${arm}.lookup.validation.log"
      return 1
    fi
    printf 'PASS hit_rate=%s minimum=0.99\n' "${lookup_rate}" \
      | tee "${log_dir}/${sequence}_${arm}.lookup.validation.log"
  else
    if ! docker run --rm \
      --user "$(id -u):$(id -g)" \
      -v "${repo_root}:/repo:ro" \
      -v "${dataset_root}:/data" \
      "${stage1_image}" \
      python3 /repo/conformal/stage3_eval/validate_stock_pilot.py \
        --dump "${output}" \
        --max-ate-rmse-m 1.0 \
        --min-feature-candidates 1000 \
      2>&1 | tee "${log_dir}/${sequence}_${arm}.sanity.log"; then
      failures+=("${sequence}_${arm}:stock-trajectory-sanity")
      return 1
    fi
  fi
  return 0
}

# A new stock pilot is mandatory. It supplies inference diagnostics and exact
# feature identities generated by this same runner build.
for sequence in "${sequences[@]}"; do
  if ! run_filter "${sequence}" stock; then
    break
  fi
done

if [[ "${#failures[@]}" -ne 0 ]]; then
  printf '%s\n' "${failures[@]}" | tee "${report_dir}/stage3_failures.txt"
  exit 1
fi

docker run --rm \
  --user "$(id -u):$(id -g)" \
  -v "${repo_root}:/repo:ro" \
  -v "${dataset_root}:/data" \
  "${stage1_image}" \
  python3 /repo/conformal/stage3_eval/export_stage3_inputs.py \
    --stage1-dir /data/conformal_dumps/stage3_all11/runs \
    --input-pattern '{sequence}_stock.h5' \
    --netb-target-dir /data/conformal_dumps/stage2/netb_targets \
    --out-dir /data/conformal_dumps/stage3_all11/inputs \
    --sequences "${sequences[@]}" \
  2>&1 | tee "${log_dir}/export_stage3_inputs.log"

docker run --rm \
  --user "$(id -u):$(id -g)" \
  -e OMP_NUM_THREADS=16 \
  -v "${repo_root}:/repo:ro" \
  -v "${dataset_root}:/data" \
  -w /repo/conformal/stage2_train \
  "${pytorch_image}" \
  python3 /repo/conformal/stage3_eval/build_sigma_sidecars.py \
    --input-dir /data/conformal_dumps/stage3_all11/inputs \
    --net-a /data/conformal_dumps/stage2/checkpoints/netA_geomvalid_seed7_epoch50_lr3e-4.pt \
    --net-b /data/conformal_dumps/stage2/checkpoints/netB_guarded_seed7_maxepoch50_lr3e-4.pt \
    --conformal /data/conformal_dumps/stage2/conformal/conformal_alpha0.10.json \
    --out-dir /data/conformal_dumps/stage3_all11/predictions \
    --sequences "${sequences[@]}" \
  2>&1 | tee "${log_dir}/build_sigma_sidecars.log"

docker run --rm \
  --user "$(id -u):$(id -g)" \
  -v "${repo_root}:/repo:ro" \
  -v "${dataset_root}:/data" \
  "${stage1_image}" \
  python3 /repo/conformal/stage3_eval/convert_sigma_npz_to_h5.py \
    --input-dir /data/conformal_dumps/stage3_all11/predictions \
    --out-dir /data/conformal_dumps/stage3_all11/sidecars \
  2>&1 | tee "${log_dir}/convert_sigma_npz_to_h5.log"

docker run --rm \
  --user "$(id -u):$(id -g)" \
  -v "${repo_root}:/repo:ro" \
  -v "${dataset_root}:/data" \
  "${stage1_image}" \
  python3 /repo/conformal/stage3_eval/validate_sigma_sidecars.py \
    --sidecar-dir /data/conformal_dumps/stage3_all11/sidecars \
    --expected 44 \
  2>&1 | tee "${log_dir}/validate_sigma_sidecars.log"

abort_nonstock=false
for sequence in "${sequences[@]}"; do
  for arm in "${nonstock_arms[@]}"; do
    if ! run_filter "${sequence}" "${arm}"; then
      abort_nonstock=true
      break
    fi
  done
  if [[ "${abort_nonstock}" == true ]]; then
    break
  fi
done

if [[ "${#failures[@]}" -eq 0 ]]; then
  if ! docker run --rm \
    --user "$(id -u):$(id -g)" \
    -v "${repo_root}:/repo:ro" \
    -v "${dataset_root}:/data" \
    "${stage1_image}" \
    python3 /repo/conformal/stage3_eval/evaluate_stage3_runs.py \
      --run-dir /data/conformal_dumps/stage3_all11/runs \
      --log-dir /data/conformal_dumps/stage3_all11/logs \
      --out-dir /data/conformal_dumps/stage3_all11/reports \
      --min-hit-rate 0.99 \
      --sequences "${sequences[@]}" \
    2>&1 | tee "${log_dir}/evaluate_stage3_runs.log"; then
    failures+=("evaluation-or-sigma-lookup-validation")
  fi
fi

if [[ "${#failures[@]}" -ne 0 ]]; then
  printf '%s\n' "${failures[@]}" | tee "${report_dir}/stage3_failures.txt"
fi

printf '%s\n' \
  "method=two-pass offline stock-pilot inference" \
  "primary_split=MH_05_difficult,V2_02_medium,V2_03_difficult" \
  "supplementary_splits=train,calibration" \
  "visual_lookup=exact timestamp_us and feature_id" \
  "minimum_lookup_hit_rate=0.99" \
  "inertial_model=accepted epoch-zero constant-Q correction" \
  > "${report_dir}/stage3_methodology.txt"

(
  cd "${stage3_dir}"
  find inputs predictions sidecars runs logs reports -type f -print0 \
    | sort -z \
    | xargs -0 sha256sum > stage3_all11_checksums.sha256
)

echo "Stage-3 all-11 benchmark complete: ${stage3_dir}"
if [[ "${#failures[@]}" -ne 0 ]]; then
  exit 1
fi
